using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace WolfEngine.SourceGenerators.Serialization;

internal sealed class SerializationRoot
{
	public SerializationRoot(ObjectModel model, string key, bool isComponent)
	{
		Model = model;
		Key = key;
		IsComponent = isComponent;
	}

	public ObjectModel Model { get; }

	public string Key { get; }

	public bool IsComponent { get; }
}

/// <summary>Writes the C# source for one assembly's serializers and their registration.</summary>
internal sealed class SerializerEmitter
{
	private const string Writer = "global::WolfEngine.Serialization.BinaryAssetWriter";
	private const string Reader = "global::WolfEngine.Serialization.BinaryAssetReader";
	private const string Registry = "global::WolfEngine.Serialization.SerializedTypeRegistry";
	private const string UnsafeAccessor = "global::System.Runtime.CompilerServices.UnsafeAccessor";
	private const string UnsafeAccessorKind = "global::System.Runtime.CompilerServices.UnsafeAccessorKind";

	private readonly StringBuilder _source = new();
	private readonly Dictionary<TypeModel, bool> _emittable = new();
	private int _indent;
	private int _nextAccessorId;

	public string Emit(string assemblyName, IReadOnlyList<SerializationRoot> roots, IReadOnlyList<TypeModel> helperModels)
	{
		Line("// <auto-generated/>");
		Line("// Binary cooked-data serializers generated by WolfEngine.SourceGenerators.");
		Line("#nullable disable");
		Line("#pragma warning disable CS0612, CS0618, CA2255");
		Line();
		Line("namespace WolfEngine.Serialization.Generated");
		Open();
		Line($"internal static class WolfBinarySerializers_{Sanitize(assemblyName)}");
		Open();

		EmitRegistration(roots);

		foreach (var model in helperModels)
		{
			if (IsEmittable(model) == false)
			{
				continue;
			}

			Line();
			EmitHelpers(model);
		}

		Line();
		EmitCallbackHelpers();

		Close();
		Close();

		return _source.ToString();
	}

	public bool IsEmittable(TypeModel model)
	{
		if (_emittable.TryGetValue(model, out var known))
		{
			return known;
		}

		// Assume true while visiting so self-referencing types terminate; any failure below still sticks.
		_emittable[model] = true;
		var result = model switch
		{
			ScalarModel => true,
			UnsupportedModel => false,
			NullableModel nullable => IsEmittable(nullable.Inner),
			CollectionModel collection => IsEmittable(collection.Element),
			DictionaryModel dictionary => IsEmittable(dictionary.Key) && IsEmittable(dictionary.Value),
			ObjectModel obj => obj.HasErrors == false && obj.MembersInLayoutOrder.All(member => IsEmittable(member.Type)),
			_ => false
		};
		_emittable[model] = result;

		return result;
	}

	private void EmitRegistration(IReadOnlyList<SerializationRoot> roots)
	{
		Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
		Line("internal static void Register()");
		Open();
		foreach (var root in roots)
		{
			if (IsEmittable(root.Model) == false)
			{
				continue;
			}

			var hash = LayoutHash.Compute(root.Model);
			var kind = root.IsComponent
				? "global::WolfEngine.Serialization.SerializedComponentType"
				: "global::WolfEngine.Serialization.SerializedDataAssetType";
			Line($"{Registry}.Register(new {kind}<{root.Model.TypeName}>(");
			_indent++;
			Line($"{SymbolDisplay.FormatLiteral(root.Key, true)},");
			Line($"0x{hash:X16}UL,");
			Line($"W{root.Model.HelperId},");
			Line($"R{root.Model.HelperId}));");
			_indent--;
		}

		Close();
	}

	private void EmitHelpers(TypeModel model)
	{
		Line($"// {model.TypeName.Replace("global::", string.Empty)}");
		switch (model)
		{
			case NullableModel nullable:
				EmitNullable(nullable);
				break;

			case CollectionModel collection:
				EmitCollection(collection);
				break;

			case DictionaryModel dictionary:
				EmitDictionary(dictionary);
				break;

			case ObjectModel obj:
				EmitObject(obj);
				break;
		}
	}

	private void EmitNullable(NullableModel model)
	{
		var id = model.HelperId;
		Line($"private static void W{id}({Writer} writer, in {model.TypeName} value)");
		Open();
		Line("writer.WritePresence(value.HasValue);");
		Line("if (value.HasValue)");
		Open();
		WriteValue(model.Inner, "value.Value");
		Close();
		Close();
		Line();
		Line($"private static {model.TypeName} R{id}(ref {Reader} reader)");
		Open();
		Line("if (reader.ReadPresence() == false)");
		Open();
		Line("return null;");
		Close();
		Line();
		Line($"return {ReadValue(model.Inner)};");
		Close();
	}

	private void EmitCollection(CollectionModel model)
	{
		var id = model.HelperId;
		var element = model.Element.TypeName;
		Line($"private static void W{id}({Writer} writer, in {model.TypeName} value)");
		Open();
		Line("if (value is null)");
		Open();
		Line("writer.WriteNull();");
		Line("return;");
		Close();
		Line();
		if (model.Kind == CollectionKind.Array)
		{
			Line("writer.WriteCount(value.Length);");
			Line("for (var i = 0; i < value.Length; i++)");
			Open();
			WriteValue(model.Element, "value[i]");
			Close();
		}
		else
		{
			// Interface-typed members may hold any collection, so count through the read-only view or a copy.
			Line($"var items = value as global::System.Collections.Generic.IReadOnlyCollection<{element}> ?? new global::System.Collections.Generic.List<{element}>(value);");
			Line("writer.WriteCount(items.Count);");
			Line("foreach (var item in items)");
			Open();
			WriteValue(model.Element, "item");
			Close();
		}

		Close();
		Line();
		Line($"private static {model.TypeName} R{id}(ref {Reader} reader)");
		Open();
		Line("var count = reader.ReadCount();");
		Line("if (count < 0)");
		Open();
		Line("return null;");
		Close();
		Line();
		switch (model.Kind)
		{
			case CollectionKind.Array:
				Line($"var result = {NewArray(element, "count")};");
				Line("for (var i = 0; i < count; i++)");
				Open();
				Line($"result[i] = {ReadValue(model.Element)};");
				Close();
				break;

			case CollectionKind.List:
				Line($"var result = new global::System.Collections.Generic.List<{element}>(count);");
				Line("for (var i = 0; i < count; i++)");
				Open();
				Line($"result.Add({ReadValue(model.Element)});");
				Close();
				break;

			case CollectionKind.Set:
				Line($"var result = new global::System.Collections.Generic.HashSet<{element}>(count);");
				Line("for (var i = 0; i < count; i++)");
				Open();
				Line($"result.Add({ReadValue(model.Element)});");
				Close();
				break;
		}

		Line();
		Line("return result;");
		Close();
	}

	private void EmitDictionary(DictionaryModel model)
	{
		var id = model.HelperId;
		Line($"private static void W{id}({Writer} writer, in {model.TypeName} value)");
		Open();
		Line("if (value is null)");
		Open();
		Line("writer.WriteNull();");
		Line("return;");
		Close();
		Line();
		Line($"var items = (global::System.Collections.Generic.IReadOnlyCollection<global::System.Collections.Generic.KeyValuePair<{model.Key.TypeName}, {model.Value.TypeName}>>)value;");
		Line("writer.WriteCount(items.Count);");
		Line("foreach (var pair in items)");
		Open();
		WriteValue(model.Key, "pair.Key");
		WriteValue(model.Value, "pair.Value");
		Close();
		Close();
		Line();
		Line($"private static {model.TypeName} R{id}(ref {Reader} reader)");
		Open();
		Line("var count = reader.ReadCount();");
		Line("if (count < 0)");
		Open();
		Line("return null;");
		Close();
		Line();
		Line($"var result = new global::System.Collections.Generic.Dictionary<{model.Key.TypeName}, {model.Value.TypeName}>(count);");
		Line("for (var i = 0; i < count; i++)");
		Open();
		Line($"var key = {ReadValue(model.Key)};");
		Line($"result[key] = {ReadValue(model.Value)};");
		Close();
		Line();
		Line("return result;");
		Close();
	}

	private void EmitObject(ObjectModel model)
	{
		var id = model.HelperId;
		foreach (var member in model.MembersInLayoutOrder)
		{
			if (member.GetKind != MemberGetKind.Direct || member.SetKind != MemberSetKind.Direct)
			{
				member.AccessorId = _nextAccessorId++;
				EmitAccessors(member);
			}
		}

		if (model.UsesConstructorAccessor)
		{
			var parameters = model.ConstructorArguments
				.Select((argument, index) => $"{argument.Type.TypeName} a{index}");
			Line($"[{UnsafeAccessor}({UnsafeAccessorKind}.Constructor)]");
			Line($"private static extern {model.TypeName} C{id}({string.Join(", ", parameters)});");
			Line();
		}

		Line($"private static void W{id}({Writer} writer, in {model.TypeName} value)");
		Open();
		if (model.IsClass)
		{
			Line("if (value is null)");
			Open();
			Line("writer.WritePresence(false);");
			Line("return;");
			Close();
			Line();
			Line("writer.WritePresence(true);");
		}

		foreach (var member in model.MembersInLayoutOrder)
		{
			WriteValue(member.Type, GetMemberExpression(model, member));
		}

		Close();
		Line();
		Line($"private static {model.TypeName} R{id}(ref {Reader} reader)");
		Open();
		if (model.IsClass)
		{
			Line("if (reader.ReadPresence() == false)");
			Open();
			Line("return null;");
			Close();
			Line();
		}

		for (var i = 0; i < model.ConstructorArguments.Count; i++)
		{
			Line($"var a{i} = {ReadValue(model.ConstructorArguments[i].Type)};");
		}

		Line($"var value = {CreateInstance(model)};");
		if (model.CallsOnDeserializing)
		{
			Line("CallOnDeserializing(ref value);");
		}

		foreach (var member in model.Members)
		{
			Line(SetMemberStatement(model, member, ReadValue(member.Type)));
		}

		if (model.CallsOnDeserialized)
		{
			Line("CallOnDeserialized(ref value);");
		}

		Line();
		Line("return value;");
		Close();
	}

	private static string CreateInstance(ObjectModel model)
	{
		var arguments = string.Join(", ", model.ConstructorArguments.Select((_, index) => $"a{index}"));
		if (model.UsesConstructorAccessor)
		{
			return $"C{model.HelperId}({arguments})";
		}

		if (model.IsClass || model.HasDeclaredParameterlessConstructor || model.Constructor is not null)
		{
			return $"new {model.TypeName}({arguments})";
		}

		return $"default({model.TypeName})";
	}

	private void EmitAccessors(MemberModel member)
	{
		var target = member.DeclaringTypeIsClass ? member.DeclaringTypeName : $"ref {member.DeclaringTypeName}";
		var memberType = member.Type.TypeName;
		var id = member.AccessorId;
		if (member.Symbol is IFieldSymbol)
		{
			Line($"[{UnsafeAccessor}({UnsafeAccessorKind}.Field, Name = \"{member.Name}\")]");
			Line($"private static extern ref {memberType} A{id}Field({target} target);");
			Line();
			return;
		}

		if (member.GetKind == MemberGetKind.GetterAccessor)
		{
			Line($"[{UnsafeAccessor}({UnsafeAccessorKind}.Method, Name = \"get_{member.Name}\")]");
			Line($"private static extern {memberType} A{id}Get({target} target);");
			Line();
		}

		if (member.SetKind == MemberSetKind.SetterAccessor)
		{
			Line($"[{UnsafeAccessor}({UnsafeAccessorKind}.Method, Name = \"set_{member.Name}\")]");
			Line($"private static extern void A{id}Set({target} target, {memberType} value);");
			Line();
		}
	}

	private static string GetMemberExpression(ObjectModel owner, MemberModel member)
	{
		var target = owner.IsClass
			? "value"
			: "ref global::System.Runtime.CompilerServices.Unsafe.AsRef(in value)";
		switch (member.GetKind)
		{
			case MemberGetKind.FieldAccessor:
				return $"A{member.AccessorId}Field({target})";

			case MemberGetKind.GetterAccessor:
				return $"A{member.AccessorId}Get({target})";

			default:
				return $"value.{Identifier(member.Name)}";
		}
	}

	private static string SetMemberStatement(ObjectModel owner, MemberModel member, string valueExpression)
	{
		var target = owner.IsClass ? "value" : "ref value";
		switch (member.SetKind)
		{
			case MemberSetKind.FieldAccessor:
				return $"A{member.AccessorId}Field({target}) = {valueExpression};";

			case MemberSetKind.SetterAccessor:
				return $"A{member.AccessorId}Set({target}, {valueExpression});";

			default:
				return $"value.{Identifier(member.Name)} = {valueExpression};";
		}
	}

	private void WriteValue(TypeModel model, string expression)
	{
		if (model is ScalarModel scalar)
		{
			var argument = scalar.EnumUnderlyingTypeName is null
				? expression
				: $"({scalar.EnumUnderlyingTypeName})({expression})";
			Line($"writer.Write{scalar.MethodSuffix}({argument});");
			return;
		}

		Line($"W{model.HelperId}(writer, {expression});");
	}

	private static string ReadValue(TypeModel model)
	{
		if (model is ScalarModel scalar)
		{
			var read = $"reader.Read{scalar.MethodSuffix}()";
			return scalar.EnumUnderlyingTypeName is null ? read : $"({scalar.TypeName}){read}";
		}

		return $"R{model.HelperId}(ref reader)";
	}

	private void EmitCallbackHelpers()
	{
		Line("private static void CallOnDeserializing<TValue>(ref TValue value)");
		_indent++;
		Line("where TValue : global::System.Text.Json.Serialization.IJsonOnDeserializing");
		_indent--;
		Open();
		Line("value.OnDeserializing();");
		Close();
		Line();
		Line("private static void CallOnDeserialized<TValue>(ref TValue value)");
		_indent++;
		Line("where TValue : global::System.Text.Json.Serialization.IJsonOnDeserialized");
		_indent--;
		Open();
		Line("value.OnDeserialized();");
		Close();
	}

	/// <summary>Allocates an array whose elements may themselves be arrays: <c>new int[count][]</c>, not <c>new int[][count]</c>.</summary>
	private static string NewArray(string elementTypeName, string count)
	{
		var suffix = string.Empty;
		var baseName = elementTypeName;
		while (baseName.EndsWith("[]", System.StringComparison.Ordinal))
		{
			baseName = baseName.Substring(0, baseName.Length - 2);
			suffix += "[]";
		}

		return $"new {baseName}[{count}]{suffix}";
	}

	private static string Identifier(string name)
	{
		return SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;
	}

	private static string Sanitize(string name)
	{
		var builder = new StringBuilder(name.Length);
		foreach (var character in name)
		{
			builder.Append(char.IsLetterOrDigit(character) ? character : '_');
		}

		return builder.ToString();
	}

	private void Open()
	{
		Line("{");
		_indent++;
	}

	private void Close()
	{
		_indent--;
		Line("}");
	}

	private void Line(string text = "")
	{
		if (text.Length > 0)
		{
			_source.Append('\t', _indent);
			_source.Append(text);
		}

		_source.Append('\n');
	}
}
